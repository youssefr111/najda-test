-- Published legal versions can never be edited or deleted, so the text a user accepted
-- can always be shown exactly as it was.
CREATE FUNCTION public.forbid_legal_version_changes() RETURNS trigger
    LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'Published legal document versions are immutable';
END;
$$;

CREATE TRIGGER trg_legal_document_versions_immutable
    BEFORE UPDATE OR DELETE ON public.legal_document_versions
    FOR EACH ROW EXECUTE FUNCTION public.forbid_legal_version_changes();

